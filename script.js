// ===============================
// Функция рендеринга
// ===============================
const postsContainer = document.getElementById('postsContainer');

function renderArticles(articlesArray) {
    // очищаем контейнер чтобы статьи не дублировались
    postsContainer.innerHTML = '';

    if (articlesArray.length === 0) {
        postsContainer.innerHTML = '<p class="no-results">Ничего не найдено 😢</p>';
        return;
    }

    articlesArray.forEach(article => {
        // если у темы есть картинка - добавляем figure
        let imageHtml = '';
        if (article.image != '') {
            imageHtml = `
                <figure>
                    <img src="${article.image}" alt="${article.title}">
                    <figcaption>${article.imageCaption}</figcaption>
                </figure>
            `;
        }

        // дата есть не у всех тем
        let dateHtml = '';
        if (article.date) {
            dateHtml = `<p>Год: <time datetime="${article.isoDate}">${article.date}</time></p>`;
        }

        const articleHtml = `
            <article>
                <header>
                    <h3>${article.id}. ${article.title}</h3>
                    ${dateHtml}
                </header>
                ${imageHtml}
                <p class="article-text short">${article.text}</p>
                <button class="read-more-btn">Читать далее</button>
                <footer>
                    <p>Теги: ${article.tags}</p>
                    <button class="like-btn">❤️ Понятно (<span class="like-count">0</span>)</button>
                </footer>
            </article>
        `;

        postsContainer.insertAdjacentHTML('beforeend', articleHtml);
    });

    // кнопки создаются заново при каждом рендере,
    // поэтому обработчики тоже надо вешать заново
    addLikeButtons();
    addReadMoreButtons();
}


// ===============================
// ПР4. Лайки
// ===============================
function addLikeButtons() {
    const likeButtons = document.querySelectorAll('.like-btn');

    likeButtons.forEach(function(button) {
        button.addEventListener('click', function() {
            const countSpan = button.querySelector('.like-count');
            let currentLikes = parseInt(countSpan.textContent);
            currentLikes++;
            countSpan.textContent = currentLikes;

            button.style.backgroundColor = '#e74c3c';
            button.style.color = 'white';
        });
    });
}


// ===============================
// ПР4. Читать далее / Свернуть
// ===============================
function addReadMoreButtons() {
    const readMoreButtons = document.querySelectorAll('.read-more-btn');

    readMoreButtons.forEach(function(btn) {
        btn.addEventListener('click', function() {
            const textBlock = btn.previousElementSibling;
            textBlock.classList.toggle('short');

            if (textBlock.classList.contains('short')) {
                btn.textContent = 'Читать далее';
            } else {
                btn.textContent = 'Свернуть';
            }
        });
    });
}

// первый рендер при загрузке
renderArticles(initialArticles);


